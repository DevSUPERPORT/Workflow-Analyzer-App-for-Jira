export const DICT = { en, de };

export function normalizeLang(l) {
  const s = String(l || '').toLowerCase();
  return s.startsWith('de') ? 'de' : 'en';
}

export function t(lang, key, vars) {
  const d = DICT[normalizeLang(lang)];
  let s = d[key] ?? en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return s;
}

export function formatDate(lang, iso, withTime = true) {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  return d.toLocaleString(normalizeLang(lang) === 'de' ? 'de-DE' : 'en-GB', withTime ? { dateStyle: 'medium', timeStyle: 'short' } : { dateStyle: 'medium' });
}

export function findingText(lang, f) {
  const params = { ...(f.params || {}), wf: f.wfName, rule: f.ruleLabel || '' };
  if (params.type) params.type = t(lang, `ref.${params.type}`);
  return { title: t(lang, `finding.${f.code}.title`, params), fix: t(lang, `finding.${f.code}.fix`, params) };
}
